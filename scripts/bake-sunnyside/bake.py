"""Bake the Sunnyside World art pack into Agent Quest's processed asset tree.

Usage:
  python3 scripts/bake-sunnyside/bake.py [--only heroes,terrain,...]

Reads the purchased pack zips (never extracted into the repo), writes
processed PNGs under client/public/assets/themes/sunnyside/ and the generated
sheet metadata TS at client/src/game/themes/sunnyside-sheet.ts.
Requires Pillow (pip install pillow).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))

from common import Sources  # noqa: E402

DEFAULT_PACK = REPO / ".context/attachments/OYDUJv/Sunnyside_World_ASSET_PACK_V2.1.zip"
DEFAULT_ARCHIVED = REPO / ".context/attachments/lNzwXE/Sunnyside_World_ARCHIVED_ASSETS.zip"
OUT = REPO / "client/public/assets/themes/sunnyside"
GENERATED_TS = REPO / "client/src/game/themes/sunnyside-sheet.ts"


def write_generated_ts(meta: dict) -> None:
    body = json.dumps(meta, indent=2)
    GENERATED_TS.write_text(
        "// GENERATED by scripts/bake-sunnyside/bake.py — do not edit by hand.\n"
        "// Re-run the bake after changing the pack or the bake scripts.\n"
        f"export const SUNNYSIDE_SHEET = {body} as const;\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--pack", type=Path, default=DEFAULT_PACK)
    parser.add_argument("--archived", type=Path, default=DEFAULT_ARCHIVED)
    parser.add_argument("--out", type=Path, default=OUT)
    parser.add_argument("--only", type=str, default="", help="comma-separated subset of steps")
    args = parser.parse_args()

    only = {s.strip() for s in args.only.split(",") if s.strip()}

    def enabled(step: str) -> bool:
        return not only or step in only

    src = Sources.open(args.pack, args.archived)

    meta_path = args.out / "bake-meta.json"
    meta: dict = json.loads(meta_path.read_text()) if meta_path.exists() else {}

    if enabled("heroes"):
        from heroes import bake_goblins, bake_heroes, bake_skeleton

        meta["heroes"] = bake_heroes(src, args.out)
        meta["goblin"] = bake_goblins(src, args.out)
        meta["skeleton"] = bake_skeleton(src, args.out)
        print("baked heroes")
    if enabled("terrain"):
        from terrain import bake_terrain

        meta["terrain"] = bake_terrain(src, args.out)
        print("baked terrain")
    if enabled("buildings"):
        from buildings import bake_buildings

        meta["buildings"] = bake_buildings(src, args.out)
        print("baked buildings")
    if enabled("scenery"):
        from scenery import bake_scenery

        meta["scenery"] = bake_scenery(src, args.out)
        print("baked scenery")
    if enabled("vfx"):
        from vfx import bake_vfx

        meta["vfx"] = bake_vfx(src, args.out)
        print("baked vfx")
    if enabled("ui"):
        from ui import bake_ui

        meta["ui"] = bake_ui(src, REPO / "client/public/assets/ui/sunnyside")
        print("baked ui")

    meta_path.parent.mkdir(parents=True, exist_ok=True)
    meta_path.write_text(json.dumps(meta, indent=2) + "\n")
    write_generated_ts(meta)
    print(f"wrote {meta_path.relative_to(REPO)} and {GENERATED_TS.relative_to(REPO)}")


if __name__ == "__main__":
    main()
