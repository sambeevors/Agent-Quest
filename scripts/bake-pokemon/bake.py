"""Bake PokéAgent's world: Cerulean City, its trainers and their Pokémon.

Usage:
  python3 scripts/bake-pokemon/bake.py --firered <pret/pokefirered checkout> --pokeapi <PokeAPI/sprites checkout>

Educational/non-commercial fork only: the art belongs to Nintendo / Game
Freak / The Pokémon Company. Two sources, neither copied into the repo:

- pret/pokefirered (the FireRed decompilation) for everything that isn't a
  Pokémon: the town is rendered straight from the decomp's map data
  (`town.py`), the trainers come from its trainer table (`trainers.py`), and
  their overworld sprites and battle portraits carry their in-game palettes
  (`overworld.py`).
- PokeAPI/sprites for the Pokémon: Gen III party icons for the partners that
  follow each trainer and the Pokémon facing them on Nugget Bridge.

A sparse checkout is enough:
  firered: data/tilesets data/layouts data/maps/{CeruleanCity,Route4,Route5,Route9,Route24}
           graphics/object_events graphics/trainers graphics/door_anims
           src/data/object_events src/data/trainers.h src/data/trainer_parties.h
           include/constants/species.h
  pokeapi: sprites/pokemon/versions/generation-iii/icons

Writes PNGs under client/public/assets/pokemon/ and three generated modules:
the town (client/src/game/town/town-data.ts), the trainer roster
(client/src/naming/trainer-roster.ts) and sprite metrics
(client/src/game/pokemon-sheet.ts). Requires Pillow.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parent))

from frlg import _read_pal  # noqa: E402
from overworld import Overworld, walker_sheet  # noqa: E402
from town import bake_town  # noqa: E402
from trainers import rockets, roster  # noqa: E402

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / 'client/public/assets/pokemon'
TOWN_TS = REPO / 'client/src/game/town/town-data.ts'
ROSTER_TS = REPO / 'client/src/naming/trainer-roster.ts'
SHEET_TS = REPO / 'client/src/game/pokemon-sheet.ts'

# Everything is drawn at x2: one 16px block is 32 world px.
Z = 2

# The Rocket on Nugget Bridge sends out Ekans and Zubat; they hold the
# bridge's north end against whoever is running commands.
ARENA = [23, 41]

GENERATED = '// GENERATED by scripts/bake-pokemon/bake.py — do not edit by hand.\n'


def scale(img: Image.Image, k: int = Z) -> Image.Image:
    return img.resize((img.width * k, img.height * k), Image.NEAREST)


def save(img: Image.Image, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    img.save(path, optimize=True)


def bbox_extent(img: Image.Image) -> tuple[int, int]:
    """(top opaque row, row below the lowest opaque pixel)."""
    box = img.getchannel('A').getbbox()
    return (box[1], box[3]) if box else (0, img.height)


def load_icon(pokeapi: Path, dex: int) -> Image.Image:
    im = Image.open(pokeapi / 'sprites/pokemon/versions/generation-iii/icons' / f'{dex}.png')
    return im.convert('RGBA')


def icon_strip(pokeapi: Path, dex: int) -> Image.Image:
    """Two frames: the icon, and the icon one pixel lower — the party-menu hop."""
    icon = load_icon(pokeapi, dex)
    strip = Image.new('RGBA', (64, 32), (0, 0, 0, 0))
    strip.alpha_composite(icon, (0, 0))
    strip.alpha_composite(icon.crop((0, 0, 32, 31)), (32, 1))
    return strip


def bake_pokemon(pokeapi: Path, out: Path, partners: list[int]) -> dict:
    # Arena residents: idle hop, then a lunge-and-flash attack loop.
    arena = []
    for i, dex in enumerate(ARENA, start=1):
        icon = load_icon(pokeapi, dex)
        flash = icon.copy()
        fp = flash.load()
        for yy in range(32):
            for xx in range(32):
                if fp[xx, yy][3]:
                    fp[xx, yy] = (248, 248, 248, 255)
        frames = [(icon, 0, 0), (icon, 0, 1), (icon, -4, 0), (flash, -4, 0)]
        sheet = Image.new('RGBA', (32 * len(frames), 32), (0, 0, 0, 0))
        for j, (im, dx, dy) in enumerate(frames):
            sheet.alpha_composite(im.crop((max(0, -dx), 0, 32, 32 - dy)), (j * 32 + max(0, dx), dy))
        save(sheet, out / 'pokemon' / f'wild-{i}.png')
        head, foot = bbox_extent(icon)
        arena.append({'key': f'wild-{i}', 'headY': head, 'footY': foot})
    # Partners — two-frame hop strips. Icons sit on a common baseline, so
    # one extent (the typical one) serves them all.
    heads, feet = [], []
    for dex in partners:
        save(icon_strip(pokeapi, dex), out / 'pokemon' / f'{dex}.png')
        head, foot = bbox_extent(load_icon(pokeapi, dex))
        heads.append(head)
        feet.append(foot)
    heads.sort()
    feet.sort()
    extent = {'frameHeight': 32, 'headY': heads[len(heads) // 2], 'footY': feet[len(feet) // 2]}
    return {'arena': arena, 'partners': partners, 'partnerExtent': extent}


def bake_trainers(root: Path, out: Path, entries: list[dict]) -> dict:
    """One walker sheet per overworld sprite, one portrait per battle pic."""
    ow = Overworld(root)
    heads, feet = [], []
    sprites = sorted({e['sprite'] for e in entries})
    for name in sprites:
        sheet = ow.load(f'people/{name}')
        if sheet.width < 16 * 9:
            raise ValueError(f'{name} has no walk cycle ({sheet.width}px wide)')
        walker = walker_sheet(sheet)
        save(walker, out / 'trainers' / f'{name}.png')
        h, f = bbox_extent(walker.crop((0, 0, 16, 32)))
        heads.append(h)
        feet.append(f)
    portraits = sorted({e['portrait'] for e in entries})
    for name in portraits:
        save(portrait(root, name), out / 'portraits' / f'{name}.png')
    return {
        'frameWidth': 16, 'frameHeight': 32,
        'headY': min(heads), 'footY': max(feet),
        'sprites': sprites, 'portraits': portraits,
    }


def portrait(root: Path, name: str) -> Image.Image:
    im = Image.open(root / f'graphics/trainers/front_pics/{name}_front_pic.png')
    pal = root / f'graphics/trainers/palettes/{name}.pal'
    im = im.copy()
    if pal.exists():
        flat = [c for rgb in _read_pal(pal) for c in rgb[:3]]
        im.putpalette(flat + [0] * (768 - len(flat)))
    idx = im.load()
    rgba = im.convert('RGBA')
    o = rgba.load()
    for yy in range(im.height):
        for xx in range(im.width):
            if idx[xx, yy] == 0:
                o[xx, yy] = (0, 0, 0, 0)
    # Square-crop to the figure so the React avatar shows the trainer's face.
    box = rgba.getchannel('A').getbbox() or (0, 0, 64, 64)
    side = min(64, max(box[2] - box[0], 40))
    cx = (box[0] + box[2]) // 2
    left = max(0, min(64 - side, cx - side // 2))
    return scale(rgba.crop((left, box[1], left + side, box[1] + side)).resize((48, 48), Image.NEAREST))


def bake_ui() -> None:
    """9-slice frames for the React panels, in FireRed's menu style.

    Drawn rather than ripped: the game's window frames are 8px tiles built for
    a white text box, and every panel here keeps the app's dark interior (its
    text palette is tuned for it). So this is the battle text box's look — a
    dark slate centre in a rounded frame — at native 1x, 4px slices, for CSS
    border-image with image-rendering: pixelated.
    """
    def frame(rings: list[tuple[int, int, int, int]], fill: tuple[int, int, int, int]) -> Image.Image:
        n = len(rings)
        size = n * 2 + 1
        img = Image.new('RGBA', (size, size), fill)
        px = img.load()
        for y in range(size):
            for x in range(size):
                d = min(x, y, size - 1 - x, size - 1 - y)
                if d < n:
                    px[x, y] = rings[d]
        # Round the corners: knock out the outermost corner pixel and pull the
        # second ring in to meet the outline.
        for cx, cy in ((0, 0), (size - 1, 0), (0, size - 1), (size - 1, size - 1)):
            px[cx, cy] = (0, 0, 0, 0)
            ix = 1 if cx == 0 else size - 2
            iy = 1 if cy == 0 else size - 2
            px[ix, iy] = rings[0]
        return img

    outline = (40, 48, 64, 255)
    white = (248, 248, 248, 255)
    blue = (104, 144, 176, 255)
    slate = (40, 56, 80, 255)
    save(frame([outline, white, blue, slate], slate), OUT / 'ui' / 'box.png')
    # Header plate: FireRed's white text window — dark text on white.
    save(frame([outline, (200, 208, 216, 255), white, white], white), OUT / 'ui' / 'plate.png')


def ts(name: str, value: object) -> str:
    return GENERATED + f'export const {name} = {json.dumps(value, indent=2, ensure_ascii=False)} as const;\n'


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--firered', type=Path, default=REPO / '.context/dl/firered')
    ap.add_argument('--pokeapi', type=Path, default=REPO / '.context/dl/pokeapi')
    args = ap.parse_args()

    trainers = roster(args.firered)
    rocket = rockets()
    partners = sorted({e['partner'] for e in trainers + rocket})

    town = bake_town(args.firered, OUT, scale)
    sheet = {
        'trainers': bake_trainers(args.firered, OUT, trainers + rocket),
        'pokemon': bake_pokemon(args.pokeapi, OUT, partners),
    }
    bake_ui()

    TOWN_TS.parent.mkdir(parents=True, exist_ok=True)
    TOWN_TS.write_text(ts('TOWN_DATA', town))
    ROSTER_TS.write_text(ts('TRAINERS', trainers) + '\n' + f'export const ROCKETS = {json.dumps(rocket, indent=2, ensure_ascii=False)} as const;\n')
    SHEET_TS.write_text(ts('POKEMON_SHEET', sheet))


if __name__ == '__main__':
    main()
